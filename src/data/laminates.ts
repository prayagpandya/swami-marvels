const mapCollectionSlug = (rawCol: string) => {
  const col = rawCol.toLowerCase();
  if (col.includes('shine') || col.includes('craft')) return 'shine-craft';
  if (col.includes('wood') || col.includes('grain')) return 'woodgrain-naturals';
  if (col.includes('stone') || col.includes('mineral') || col.includes('marble')) return 'stone-mineral';
  if (col.includes('solid')) return 'solid-tone';
  if (col.includes('living') || col.includes('modern')) return 'modern-living';
  if (col.includes('artistic') || col.includes('inspired')) return 'artistic-inspired';
  return 'solid-tone';
};

const mapFinishSlug = (rawFinish: string) => {
  const fin = rawFinish.toLowerCase();
  if (fin.includes('natural') || fin.includes('grain')) return 'natural-grain';
  if (fin.includes('gloss')) return 'high-gloss';
  if (fin.includes('textur')) return 'textured';
  if (fin.includes('leather')) return 'leather-touch';
  return 'suede-matt';
};

const parseFeatures = (featStr: string) => {
  if (!featStr) return ['High Durability', 'Premium Quality'];
  return featStr.split(',').map(f => f.trim());
};

const parseApplications = (appStr: string) => {
  if (!appStr) return ['furniture', 'commercial'];
  return appStr.split(',').map(f => f.trim());
};

const getSwatchColor = (color: string) => {
  const c = color.toLowerCase();
  if (c.includes('walnut')) return '#6B4A32';
  if (c.includes('teak')) return '#7A5230';
  if (c.includes('oak')) return '#C6A87E';
  if (c.includes('grey') || c.includes('gray')) {
    if (c.includes('dark') || c.includes('charcoal')) return '#2C2A27';
    if (c.includes('light') || c.includes('pearl')) return '#A9A198';
    return '#8A8377';
  }
  if (c.includes('white')) return '#EDEAE4';
  if (c.includes('black')) return '#15130F';
  if (c.includes('green')) return '#33463C';
  if (c.includes('blue')) return '#2C3A4A';
  if (c.includes('copper')) return '#A45F35';
  if (c.includes('terracotta')) return '#B4735A';
  return '#E6DCCB';
};

